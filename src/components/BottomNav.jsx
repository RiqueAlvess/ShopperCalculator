export default function BottomNav({ active, onChange }) {
  const tabs = [
    { id: 'dashboard', label: 'Dashboard', icon: DashIcon },
    { id: 'calculator', label: 'Calc', icon: CalcIcon },
    { id: 'history', label: 'Histórico', icon: CalIcon },
    { id: 'settings', label: 'Config', icon: GearIcon },
  ]

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 bg-graphite-800 border-t border-graphite-600 safe-bottom">
      <div className="flex items-stretch h-16">
        {tabs.map(({ id, label, icon: Icon }) => {
          const isActive = active === id
          return (
            <button
              key={id}
              onClick={() => onChange(id)}
              className={`flex-1 flex flex-col items-center justify-center gap-0.5 transition-colors ${
                isActive ? 'text-neon-green' : 'text-gray-500 hover:text-gray-300'
              }`}
            >
              <Icon size={22} active={isActive} />
              <span className="text-[10px] font-medium">{label}</span>
            </button>
          )
        })}
      </div>
    </nav>
  )
}

